#!/usr/bin/env python3
"""Generate the saturation (P-T) tables used by the HP Prime program.

The calculator stores, for every refrigerant, the absolute saturation
pressure (psia) at the bubble point (liquid) and dew point (vapor) from
-40 F to 150 F in 5 F steps.  Between rows the program interpolates
linearly in ln(P), which tracks the real curve to within about 0.1 psi.

Data sources
  * R-22, R-32, R-134a, R-404A, R-407C, R-410A : CoolProp (pip install CoolProp)
  * R-454B : tools/data/R454B.csv (Chemours, NIST REFPROP 10)
  * R-448A : tools/data/R448A.csv (Arkema, NIST REFPROP 10)

Usage
  python3 tools/gen_pt_tables.py            # rewrite the data block in the program
  python3 tools/gen_pt_tables.py --check    # also print accuracy checks

To add a refrigerant: add an entry to REFRIGERANTS (CoolProp name, or a CSV
file in tools/data with columns temp_F,bubble,dew), then re-run.  The
program picks up the new count automatically.
"""
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROGRAM = os.path.join(ROOT, "hp-prime", "SUPERSUB.txt")
DATA = os.path.join(ROOT, "tools", "data")

T_MIN, T_MAX, T_STEP = -40, 150, 5
TEMPS = list(range(T_MIN, T_MAX + 1, T_STEP))
ATM = 14.696          # psia
PA_PER_PSI = 6894.757

# name shown on screen, data source, cylinder colour (r,g,b) for the UI
REFRIGERANTS = [
    ("R-22",   "coolprop:R22",            (130, 200, 80)),   # light green
    ("R-410A", "coolprop:R410A",          (235, 110, 150)),  # rose
    ("R-454B", "csv:R454B.csv:psia",      (170, 170, 175)),  # gray
    ("R-32",   "coolprop:R32",            (70, 130, 230)),   # blue
    ("R-134a", "coolprop:R134a",          (120, 190, 235)),  # light blue
    ("R-404A", "coolprop:R404A",          (245, 140, 40)),   # orange
    ("R-407C", "coolprop:R407C",          (175, 115, 70)),   # brown
    ("R-448A", "csv:R448A.csv:psig",      (80, 120, 210)),   # gentian blue
]


def f_to_k(t):
    return (t - 32) * 5 / 9 + 273.15


def sat_psia(fluid, k, q):
    """Saturation pressure; the mixture flash occasionally fails to
    converge at one exact temperature, so fall back to the mean of two
    points a few millikelvin either side."""
    import CoolProp.CoolProp as CP
    try:
        return CP.PropsSI("P", "T", k, "Q", q, fluid) / PA_PER_PSI
    except ValueError:
        for dk in (0.002, 0.005, 0.02):
            try:
                lo = CP.PropsSI("P", "T", k - dk, "Q", q, fluid)
                hi = CP.PropsSI("P", "T", k + dk, "Q", q, fluid)
                return (lo + hi) / 2 / PA_PER_PSI
            except ValueError:
                pass
        raise


def coolprop_table(fluid):
    bub = [sat_psia(fluid, f_to_k(t), 0) for t in TEMPS]
    dew = [sat_psia(fluid, f_to_k(t), 1) for t in TEMPS]
    return bub, dew


def csv_table(fname, unit):
    rows = {}
    with open(os.path.join(DATA, fname)) as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            t, b, d = line.split(",")
            off = ATM if unit == "psig" else 0.0
            rows[int(t)] = (float(b) + off, float(d) + off)
    missing = [t for t in TEMPS if t not in rows]
    if missing:
        sys.exit(f"{fname}: missing temperatures {missing}")
    return [rows[t][0] for t in TEMPS], [rows[t][1] for t in TEMPS]


def load(src):
    kind, rest = src.split(":", 1)
    if kind == "coolprop":
        return coolprop_table(rest)
    fname, unit = rest.split(":")
    return csv_table(fname, unit)


def ppl_matrix(rows):
    body = ",\n".join(
        "[" + ",".join(f"{v:.2f}" for v in r) + "]" for r in rows)
    return "[" + body + "]"


def build_block(tables):
    names = ",".join(f'"{n}"' for n, _, _ in REFRIGERANTS)
    colors = ",".join(f"RGB({r},{g},{b})" for _, _, (r, g, b) in REFRIGERANTS)
    # darker shade of the same colour, readable on the white dial face
    darks = ",".join(f"RGB({int(r*.6)},{int(g*.6)},{int(b*.6)})"
                     for _, _, (r, g, b) in REFRIGERANTS)
    out = [
        "// ---- BEGIN PT DATA (generated by tools/gen_pt_tables.py) ----",
        f"// saturation pressure in psia, {T_MIN}..{T_MAX} F every {T_STEP} F",
        f"gTmin:={T_MIN}; gTstep:={T_STEP}; gNpt:={len(TEMPS)};",
        f"gNref:={len(REFRIGERANTS)};",
        f"gRName:={{{names}}};",
        f"gRCol:={{{colors}}};",
        f"gRDk:={{{darks}}};",
        "// bubble point (liquid line / subcooling)",
        "gBub:=" + ppl_matrix([b for b, _ in tables]) + ";",
        "// dew point (suction line / superheat)",
        "gDew:=" + ppl_matrix([d for _, d in tables]) + ";",
        "// ---- END PT DATA ----",
    ]
    return "\n".join(out)


def interp(table, t):
    """Same ln(P) interpolation the calculator uses."""
    x = (t - T_MIN) / T_STEP
    k = min(max(int(math.floor(x)), 0), len(TEMPS) - 2)
    f = x - k
    return math.exp(math.log(table[k]) * (1 - f) + math.log(table[k + 1]) * f)


def check(tables):
    import CoolProp.CoolProp as CP
    print("Max interpolation error vs CoolProp at 0.5 F steps (psi):")
    for (name, src, _), (bub, dew) in zip(REFRIGERANTS, tables):
        if not src.startswith("coolprop:"):
            continue
        fluid = src.split(":", 1)[1]
        worst = 0.0
        t = T_MIN
        while t <= T_MAX:
            for q, tab in ((0, bub), (1, dew)):
                ref = sat_psia(fluid, f_to_k(t), q)
                worst = max(worst, abs(interp(tab, t) - ref))
            t += 0.5
        print(f"  {name:7s} {worst:.3f}")
    print("40 F check, psig (bubble / dew):")
    i = TEMPS.index(40)
    for (name, _, _), (bub, dew) in zip(REFRIGERANTS, tables):
        print(f"  {name:7s} {bub[i] - ATM:6.1f} / {dew[i] - ATM:6.1f}")


def main():
    tables = [load(src) for _, src, _ in REFRIGERANTS]
    for (name, _, _), (bub, dew) in zip(REFRIGERANTS, tables):
        for tab in (bub, dew):
            if any(b <= a for a, b in zip(tab, tab[1:])):
                sys.exit(f"{name}: table is not increasing")
    block = build_block(tables)
    with open(PROGRAM, encoding="utf-8") as fh:
        src = fh.read()
    pat = re.compile(r"// ---- BEGIN PT DATA.*?// ---- END PT DATA ----", re.S)
    if not pat.search(src):
        sys.exit("data markers not found in " + PROGRAM)
    src = pat.sub(lambda _: block, src)
    with open(PROGRAM, "w", encoding="utf-8") as fh:
        fh.write(src)
    print(f"wrote {len(REFRIGERANTS)} refrigerants x {len(TEMPS)} points to {PROGRAM}")
    if "--check" in sys.argv:
        check(tables)


if __name__ == "__main__":
    main()
